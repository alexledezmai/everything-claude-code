import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { detectProject } from './project-detect.js'

function walk(root, current = root, files = []) {
  for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
    if (['.git', 'node_modules', '.nes'].includes(entry.name)) continue
    const full = path.join(current, entry.name)
    if (entry.isDirectory()) walk(root, full, files)
    else files.push(path.relative(root, full).replaceAll('\\', '/'))
  }
  return files
}

function sha(value) {
  return crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex')
}

export function generateCodemap(root = process.cwd()) {
  const project = detectProject(root)
  const files = walk(root).sort()
  const groups = {
    source: files.filter((f) => /(^|\/)(src|app|pages|lib|server|api)\//.test(f)),
    tests: files.filter((f) => /(^|\/)(test|tests|__tests__|e2e)\//.test(f) || /\.(test|spec)\.[^.]+$/.test(f)),
    database: files.filter((f) => /(^|\/)(supabase|migrations|prisma|database|db)\//.test(f)),
    infrastructure: files.filter((f) => /(^|\/)(\.github|docker|infra|scripts)\//.test(f) || /(^|\/)(Dockerfile|compose\.ya?ml|docker-compose\.ya?ml)$/.test(f)),
    docs: files.filter((f) => /(^|\/)(docs|adr|architecture)\//.test(f) || /\.md$/i.test(f))
  }

  const codemap = {
    schema_version: 'nes.codemap.v1',
    generated_at: new Date().toISOString(),
    project,
    file_count: files.length,
    groups,
    files
  }
  codemap.content_sha256 = sha({ project, groups, files })
  return codemap
}

export function writeCodemap(root = process.cwd(), output = path.join(root, '.nes', 'docs', 'codemap.json')) {
  const codemap = generateCodemap(root)
  fs.mkdirSync(path.dirname(output), { recursive: true })
  fs.writeFileSync(output, JSON.stringify(codemap, null, 2))
  return { file: output, codemap }
}

export function writeAdr(root, adr) {
  if (!/^ADR-[0-9]{3,}$/.test(adr.id ?? '')) throw new Error('ADR id must match ADR-###')
  for (const field of ['title', 'status', 'context', 'decision']) {
    if (!adr[field]) throw new Error(`ADR ${field} is required`)
  }
  if (!Array.isArray(adr.consequences) || adr.consequences.length === 0) throw new Error('ADR consequences are required')

  const dir = path.join(root, '.nes', 'docs', 'adr')
  fs.mkdirSync(dir, { recursive: true })
  const jsonFile = path.join(dir, `${adr.id}.json`)
  const mdFile = path.join(dir, `${adr.id}.md`)
  const normalized = { schema_version: 'nes.adr.v1', ...adr }
  fs.writeFileSync(jsonFile, JSON.stringify(normalized, null, 2))
  fs.writeFileSync(mdFile, [
    `# ${adr.id} — ${adr.title}`,
    '',
    `**Status:** ${adr.status}`,
    '',
    '## Context',
    adr.context,
    '',
    '## Decision',
    adr.decision,
    '',
    '## Consequences',
    ...adr.consequences.map((item) => `- ${item}`),
    ...(adr.alternatives?.length ? ['', '## Alternatives', ...adr.alternatives.map((item) => `- ${item}`)] : []),
    ''
  ].join('\n'))
  return { json_file: jsonFile, markdown_file: mdFile, adr: normalized }
}

export function buildProductBible({ root = process.cwd(), product, capabilities = [], codemap = null }) {
  if (!product?.name) throw new Error('product.name is required')
  const map = codemap ?? generateCodemap(root)
  const lines = [
    `# ${product.name} — Living Product Bible`,
    '',
    '> Generated by Navi Engineering System from project-owned capability contracts and repository state.',
    '',
    '## Product',
    product.description ?? '',
    '',
    '## Engineering State',
    `- Runtime: ${map.project.runtime}`,
    `- Framework: ${map.project.framework ?? 'n/a'}`,
    `- Database: ${map.project.database ?? 'n/a'}`,
    `- Files indexed: ${map.file_count}`,
    `- Codemap SHA-256: ${map.content_sha256}`,
    '',
    '## Capabilities'
  ]

  for (const capability of capabilities) {
    lines.push('', `### ${capability.name}`, `**ID:** ${capability.id}  `, `**Status:** ${capability.status}`, '', capability.description)
    if (capability.source_paths?.length) lines.push('', '**Source of truth**', ...capability.source_paths.map((p) => `- \`${p}\``))
    if (capability.gate_ids?.length) lines.push('', `**Gates:** ${capability.gate_ids.join(', ')}`)
    if (capability.adr_ids?.length) lines.push(`**ADRs:** ${capability.adr_ids.join(', ')}`)
  }

  lines.push('', '## Generated State', `Generated: ${new Date().toISOString()}`, '')
  return lines.join('\n')
}

export function writeProductBible({ root = process.cwd(), product, capabilities = [], output }) {
  const codemap = generateCodemap(root)
  const markdown = buildProductBible({ root, product, capabilities, codemap })
  const target = output ?? path.join(root, '.nes', 'docs', 'PRODUCT-BIBLE.md')
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, markdown)
  return { file: target, codemap_sha256: codemap.content_sha256, capabilities: capabilities.length }
}
